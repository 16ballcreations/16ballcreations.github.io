/* Copies the site into dist/, the folder the Worker serves.
   Only what visitors should reach goes in: the pages and their assets.
   The Worker's code, the database migrations, the notes and the tooling
   stay out by not being on this list. */
import { cp, rm, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");

const SITE = [
  "index.html",
  /* for search engines: what to crawl, the icon, the app manifest, and the
     IndexNow key that lets us tell Bing and others when the site changes */
  "robots.txt",
  "sitemap.xml",
  /* a plain-text summary of the studio for AI tools (llmstxt.org) */
  "llms.txt",
  "favicon.ico",
  "site.webmanifest",
  "44b6eb8c5cbb6e059ea61f162a867345.txt",
  "assets",
  "mira",
  "autorizacion",
  "testimonio",
  /* one page per service, generated by scripts/servicios.mjs */
  "servicios", "proyectos",
  /* who is behind the studio, and why pool (out of the home page) */
  "estudio",
  /* política de datos (Ley 1581) y aviso de medición */
  "privacidad",
  /* the English version: home, services and MIRA under /en/ */
  "en"
  /* v1/, v2/ and v3/, the earlier versions of the home page, are kept in
     the repository as reference only: they are not published */
];

/* fonts whose license does not allow publishing them on the web stay out:
   Trebuchet MS ships with Windows and the site uses the visitor's own copy */
const NOT_PUBLISHED = /[\\/]assets[\\/]fonts[\\/]trebuc[^\\/]*\.ttf$/i;
const publishable = src => !NOT_PUBLISHED.test(src);

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
for(const entry of SITE){
  await cp(join(root, entry), join(dist, entry), { recursive: true, filter: publishable });
}
/* Microsoft Clarity (tiempo en página, scroll y mapas de calor) con su aviso:
   assets/js/medicion.js. Se agrega al publicar, al final del <head> de cada
   página, para no repetirlo en cada HTML. Quedan por fuera las páginas de
   autorización y testimonio, que son de clientes y llevan datos personales.
   Sin ID no se agrega nada. */
const CLARITY_ID = "";
const SIN_MEDICION = /^(autorizacion|testimonio)[\/]/;
let medidas = 0;
async function medir(dir, rel = ""){
  for(const item of await readdir(dir, { withFileTypes: true })){
    const sub = rel ? rel + "/" + item.name : item.name;
    if(item.isDirectory()){ await medir(join(dir, item.name), sub); continue; }
    if(!item.name.endsWith(".html") || SIN_MEDICION.test(sub)){ continue; }
    const file = join(dir, item.name);
    const html = await readFile(file, "utf8");
    if(!html.includes("</head>")){ continue; }
    const privacidad = /<html lang="en/i.test(html) ? "/en/privacy/" : "/privacidad/";
    const tag = `<script src="/assets/js/medicion.js?v=1" data-clarity="${CLARITY_ID}" data-privacidad="${privacidad}" defer></script>
`;
    await writeFile(file, html.replace("</head>", tag + "</head>"));
    medidas++;
  }
}
if(CLARITY_ID){ await medir(dist); }

console.log("dist/ listo: " + SITE.join(", ") + (CLARITY_ID ? ` · Clarity en ${medidas} páginas` : " · sin Clarity (falta CLARITY_ID)"));
